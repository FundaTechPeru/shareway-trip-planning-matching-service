-- A driver availability is a ShareWay trip group (its id is the groupId used by Booking & Pricing).
-- Same SQL for PostgreSQL and for H2 in PostgreSQL mode.

-- Group lifecycle. Existing availabilities stay OPEN.
alter table driver_availabilities add column status varchar(20) default 'OPEN' not null;
alter table driver_availabilities
    add constraint ck_driver_availabilities_status
    check (status in ('OPEN', 'ACCEPTED', 'REJECTED'));

-- Group each proposal came from. Proposals created before this migration keep it null.
alter table match_proposals add column driver_availability_id uuid;
alter table match_proposals
    add constraint fk_match_proposals_driver_availability
    foreign key (driver_availability_id) references driver_availabilities (id);
create index idx_match_proposals_driver_availability
    on match_proposals (driver_availability_id);

-- Transactional outbox of the events sent to Booking & Pricing. sequence_number keeps the order in
-- which the events were stored, even when two of them share the same occurred_at.
create table outbox (
    id uuid not null,
    sequence_number bigint generated by default as identity,
    type varchar(100) not null,
    payload varchar(4000) not null,
    occurred_at timestamp with time zone not null,
    processed_at timestamp with time zone,
    failed_at timestamp with time zone,
    attempts integer not null default 0,
    next_attempt_at timestamp with time zone not null,
    last_error varchar(1000),
    version bigint not null default 0,
    constraint pk_outbox primary key (id),
    constraint uk_outbox_sequence_number unique (sequence_number)
);

create index idx_outbox_pending
    on outbox (processed_at, failed_at, sequence_number);
